-- T019: metadata registration only. No extracted text, chunks, vectors or publication seed.
CREATE TABLE knowledge_documents (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    document_key VARCHAR(96) COLLATE utf8mb4_bin NOT NULL,
    version VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
    title VARCHAR(200) NOT NULL,
    source_type VARCHAR(32) NOT NULL,
    self_authored BOOLEAN NOT NULL,
    is_simulated BOOLEAN NOT NULL,
    model_scope VARCHAR(16) NOT NULL,
    models_json JSON NOT NULL,
    source_url VARCHAR(2048) NULL,
    official_index VARCHAR(2048) NULL,
    terms_url VARCHAR(2048) NULL,
    brand VARCHAR(64) NULL,
    region VARCHAR(64) NULL,
    language VARCHAR(32) NULL,
    acquired_on DATE NULL,
    checked_on DATE NOT NULL,
    use_condition VARCHAR(2000) NOT NULL,
    distribution_allowed BOOLEAN NOT NULL,
    external_upload_allowed BOOLEAN NOT NULL,
    local_file VARCHAR(1024) NOT NULL,
    provenance_json JSON NOT NULL,
    content_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'PENDING',
    active BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT uk_knowledge_document_version UNIQUE (document_key,version),
    CONSTRAINT ck_knowledge_source CHECK (source_type IN ('official_manual','self_authored_simulation')),
    CONSTRAINT ck_knowledge_scope CHECK (model_scope IN ('MODELS','GENERAL')),
    CONSTRAINT ck_knowledge_status CHECK (status IN ('PENDING','PROCESSING','READY','FAILED')),
    CONSTRAINT ck_knowledge_active CHECK (active=FALSE OR status='READY'),
    INDEX ix_knowledge_status_active (status,active)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE knowledge_chunks (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    document_id BIGINT NOT NULL,
    chunk_index INT NOT NULL,
    content TEXT NOT NULL,
    page_number INT NULL,
    section VARCHAR(500) NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT uk_knowledge_chunk_index UNIQUE (document_id,chunk_index),
    CONSTRAINT fk_knowledge_chunks_document FOREIGN KEY (document_id) REFERENCES knowledge_documents(id),
    CONSTRAINT ck_knowledge_chunk_index CHECK (chunk_index>=0),
    CONSTRAINT ck_knowledge_chunk_page CHECK (page_number IS NULL OR page_number>0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
